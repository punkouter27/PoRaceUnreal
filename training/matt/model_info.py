"""Matt or Grandma for Unity (trainer container, after check_model.py):
  python matt/model_info.py [--creature grandma]
- Assets/MuJoCo/matt/matt_unity.xml: the robot only, to drop into a race scene's single MuJoCo model next to the
  dogs. No option / size / statistic (the race scene's MjGlobalSettings already carries the same contract, and the
  importer would add a second settings object), no floor, light, assets or keyframes, and only the four sensors
  MattController reads (contact sensors name the trainer's floor geom).
- Assets/Scripts/<Name>Spec.cs: the contract Unity checks the regenerated model against (docs/<creature>/model_summary.json).
Both humans can share one race model: every name in Grandma's Unity files carries the prefix gm_ (Matt's none), and
the spec's Prefix says so. The trainer's floor keeps its name (world geom, shared).
"""
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import mujoco

CREATURE = sys.argv[sys.argv.index("--creature") + 1] if "--creature" in sys.argv else "matt"
# Gait clock (proposals r3 D1): Hz = gait_hz + gait_hz_slope * max(0, |vx cmd| - gait_hz_v0); the SHIPPED policy's
# values (Matt m20 and earlier: fixed 1.375; Grandma: her card, grandma/env.py). max_vx: top of the graduated race range.
CARD = {"matt": dict(cls="MattSpec", prefix="", gait_hz=1.375, gait_hz_slope=0.0, gait_hz_v0=1.2, max_vx=1.6),
        "grandma": dict(cls="GrandmaSpec", prefix="gm_", gait_hz=1.05, gait_hz_slope=0.2, gait_hz_v0=0.9, max_vx=1.2)}[CREATURE]
HERE = Path(__file__).resolve().parents[1] / CREATURE
SRC = HERE / "assets" / f"{CREATURE}_porace.xml"
UNITY = Path(f"/assets/MuJoCo/{CREATURE}/{CREATURE}_unity.xml")
SPEC = Path(f"/assets/Scripts/Core/{CARD['cls']}.cs")
SENSORS = {"local_linvel_pelvis", "gyro_pelvis", "orientation_pelvis", "upvector_torso"}
GAIT_HZ, GAIT_HZ_SLOPE, GAIT_HZ_V0 = CARD["gait_hz"], CARD["gait_hz_slope"], CARD["gait_hz_v0"]
PREFIX = CARD["prefix"]
REFS = ("name", "joint", "body1", "body2", "site", "objname", "geom1", "geom2", "target")


def prefixed(root):
  """gm_ on every name and every reference to one, except the shared floor."""
  if PREFIX:
    assets = {id(e) for a in root.findall("asset") for e in a.iter()}   # textures / materials: the shared floor's look
    for e in root.iter():
      if id(e) in assets: continue
      for k in REFS:
        v = e.get(k)
        if v and v != "floor" and not (e.tag in ("mujoco",) and k == "name"):
          e.set(k, PREFIX + v)
  return root

# Testbed (parity harness, Assets/Scenes/MattTestbed.unity): the trainer scene - option block, floor - minus keyframes
# and the sensors Unity does not use.
tb = ET.parse(SRC).getroot()
tb.set("model", f"{CREATURE} testbed")
for tag in ("size", "keyframe"):
  for e in tb.findall(tag):
    tb.remove(e)
for e in list(tb.find("sensor")):
  if e.get("name") not in {"local_linvel_pelvis", "gyro_pelvis", "orientation_pelvis", "upvector_torso"}:
    tb.find("sensor").remove(e)
if CREATURE == "matt": tb.set("model", "matt scene")   # unchanged file for Matt
prefixed(tb); ET.indent(tb)
Path(f"/assets/MuJoCo/{CREATURE}").mkdir(parents=True, exist_ok=True)
Path(f"/assets/MuJoCo/{CREATURE}/{CREATURE}_testbed.xml").write_text("<!-- generated by training/matt/model_info.py: do not edit -->\n" + ET.tostring(tb, encoding="unicode") + "\n")

root = ET.parse(SRC).getroot()
for tag in ("option", "size", "statistic", "keyframe", "asset", "visual"):
  for e in root.findall(tag):
    root.remove(e)
wb = root.find("worldbody")
for e in list(wb):
  if e.tag != "body":
    wb.remove(e)
sens = root.find("sensor")
for e in list(sens):
  if e.get("name") not in SENSORS:
    sens.remove(e)
root.set("model", CREATURE)
prefixed(root)
UNITY.parent.mkdir(parents=True, exist_ok=True)
ET.indent(root)
UNITY.write_text(f"<!-- generated by training/matt/model_info.py from {CREATURE}_porace.xml: do not edit -->\n" + ET.tostring(root, encoding="unicode") + "\n")

full = mujoco.MjModel.from_xml_path(str(SRC))
robot = mujoco.MjModel.from_xml_path(str(UNITY))
assert (robot.nq, robot.nv, robot.nu) == (full.nq, full.nv, full.nu)
assert abs(robot.body_mass.sum() - full.body_mass.sum()) < 1e-9

s = json.loads(Path(f"/docs/{CREATURE}/model_summary.json").read_text())
who = CREATURE.capitalize()
fallen = round(0.6 / 0.9265 * s["init_qpos"][2], 3)   # Matt's 0.6 m down line (MattController), scaled by stance height
fl = lambda xs: ", ".join(f"{x:g}f" for x in xs)
q = lambda xs: ", ".join(f'"{x}"' for x in xs)
SPEC.write_text(f"""// GENERATED by training/matt/model_info.py from docs/{CREATURE}/model_summary.json. Do not edit by hand.
namespace PoRace {{

/// <summary>{who} contract: G1 joint layout (29 position-controlled joints) on {who}'s body, race physics: 250 Hz,
/// 50 Hz control (decimation 5). Joint order = qpos[7:], qvel[6:], ctrl, action and observation slices.</summary>
public static class {CARD["cls"]} {{
  public const string Prefix = "{PREFIX}";   // on every MuJoCo name of this body in the Unity model (two humans share one model)
  public const int Nu = {s["nu"]};
  public const float SimDt = {s["timestep"]:g}f;
  public const int Decimation = 5;
  public const float ActionScale = 0.5f;
  public const int ObsDim = 103;   // linvel 3, gyro 3, gravity 3, command 3, q - default 29, qvel 29, last action 29, phase cos/sin 4
  public const double Mass = {s["mass"]!r};
  public const float GaitHz = {GAIT_HZ}f;
  public const float GaitHzSlope = {GAIT_HZ_SLOPE}f;   // Hz per m/s above GaitHzV0 (0: fixed clock); the shipped policy's value
  public const float GaitHzV0 = {GAIT_HZ_V0}f;
  public const float HomeHeight = {s["init_qpos"][2]:g}f;   // pelvis height at knees_bent
  public const float PelvisRestZ = {float(root.find("worldbody/body").get("pos").split()[2]):g}f;   // pelvis body at MuJoCo zero pose (= the rig's Hips head)
  public const float ImpRatio = {float(tb.find("option").get("impratio")):g}f;   // the race model is compiled at this when a human races (dogs alone: 100)
  public const float FallenPelvisZ = {fallen:g}f;   // down below this pelvis height (Matt 0.6 m, scaled by stance height)
  public const float MaxVx = {CARD["max_vx"]:g}f;   // top of the graduated race command range (m/s)
  public static readonly string[] Joints = {{ {q(s["joints"])} }};
  public static readonly float[] DefaultPose = {{ {fl(s["default_pose"])} }};
  public static readonly float[] Kp = {{ {fl(s["kp"])} }};
  public static readonly float[] ForceMax = {{ {fl(r[1] for r in s["forcerange"])} }};
}}

}}
""")
print(f"wrote {UNITY} (nq {robot.nq}, nu {robot.nu}, {robot.nsensor} sensors, mass {robot.body_mass.sum():.3f}) and {SPEC}")
